package com.vinnyvangogh.groupironman;

import org.junit.Test;
import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertTrue;

/** Region id to place name, from the bundled table. */
public class RegionNamesTest
{
	@Test
	public void theBundledTableLoadsAndKnowsLumbridge()
	{
		RegionNames names = RegionNames.load();
		assertTrue("the table should have hundreds of regions, has " + names.size(), names.size() > 500);
		assertEquals("Lumbridge", names.name(12850));
		assertEquals("Varrock", names.name(12853));
		assertEquals("Grand Exchange", names.name(12598));
		assertEquals("Vorkath", names.name(9023));
	}

	/** Board 2026-11-10: a death at the Chaos Temple read "region 11835". */
	@Test
	public void wildernessPlacesHaveNames()
	{
		RegionNames names = RegionNames.load();
		assertEquals("Chaos Temple", names.describe(11835));
		assertEquals("Ferox Enclave", names.name(12600));
		assertEquals("Edgeville Wilderness", names.name(12343));
		assertEquals("Lava Maze", names.name(12348));
		assertEquals("Graveyard of Shadows", names.name(12601));
		assertEquals("Bandit Camp (Wilderness)", names.name(12089));
		assertEquals("Mage Arena", names.name(12349));
		// The desert's Bandit Camp keeps its name; the city section comes first.
		assertEquals("Bandit Camp", names.name(12590));
		// Every other Wilderness region says so rather than a number.
		for (int x = 46; x <= 52; x++)
		{
			for (int y = 55; y <= 61; y++)
			{
				assertTrue(x + "," + y, names.name(x << 8 | y) != null);
			}
		}
		assertEquals("Wilderness", names.name(12093));
		assertEquals("Edgeville", names.name(12342));
	}

	@Test
	public void anUnknownRegionHasNoName()
	{
		assertNull(RegionNames.load().name(1));
		assertNull(RegionNames.load().name(0));
	}

	/** Board 2026-11-14: a member card read "Offline - last seen W315, region 13470". */
	@Test
	public void region13470IsTheWildernessSlayerCave()
	{
		RegionNames names = RegionNames.load();
		assertEquals("Wilderness Slayer Cave", names.name(13470));
		assertEquals("Wilderness Slayer Cave", names.describe(13470));
	}

	@Test
	public void theGeneratedTableLoadsThroughGetResourceAsStream() throws Exception
	{
		String text = resource("regions-generated.txt");
		assertTrue(text.startsWith("# GENERATED by tools/regions/gen_regions.py"));
		// A generated id regions.txt does not name: Mastering Mixology comes only from RuneLite's minigame list.
		assertEquals("Mastering Mixology", RegionNames.load().name(5421));
	}

	/** Every id either table lists resolves to a name, and the hand table wins where both list one. */
	@Test
	public void everyRegionInTheTablesResolves() throws Exception
	{
		RegionNames names = RegionNames.load();
		RegionNames hand = RegionNames.parse(resource("regions.txt"));
		RegionNames generated = RegionNames.parse(resource("regions-generated.txt"));
		assertTrue(generated.size() > 0);
		for (int id : generated.ids())
		{
			String expected = hand.name(id) != null ? hand.name(id) : generated.name(id);
			assertEquals("region " + id, expected, names.name(id));
		}
		for (int id : hand.ids())
		{
			assertEquals("region " + id, hand.name(id), names.describe(id));
		}
	}

	@Test
	public void anUnknownRegionNeverRendersItsNumber()
	{
		RegionNames full = RegionNames.load();
		RegionNames empty = RegionNames.parse("");
		for (int rx = 0; rx < 256; rx += 3)
		{
			for (int ry = 0; ry < 256; ry += 3)
			{
				int id = rx << 8 | ry;
				if (id == 0)
				{
					continue;
				}
				for (RegionNames names : new RegionNames[]{full, empty})
				{
					String text = names.describe(id);
					assertNotNull(String.valueOf(id), text);
					assertFalse(id + " -> " + text, text.matches(".*\\bregion \\d+.*"));
					// Wilderness levels are at most two digits; a region id is three to five.
					assertFalse(id + " -> " + text, text.matches(".*\\d{3,}.*"));
				}
			}
		}
	}

	@Test
	public void anUnknownRegionIsNamedAfterItsNearestNamedNeighbour()
	{
		// Lumbridge is region 50,50; Draynor is 50,52 (two regions north).
		RegionNames names = RegionNames.parse("Lumbridge=" + (50 << 8 | 50) + "\nDraynor=" + (50 << 8 | 52) + "\n");
		assertEquals("near Lumbridge", names.describe(51 << 8 | 50));
		assertEquals("near Draynor", names.describe(50 << 8 | 53));
		assertEquals("near Draynor", names.describe(51 << 8 | 54));
		// Equal distance: the lower region id wins, so the answer never depends on map order.
		assertEquals("near Lumbridge", names.describe(50 << 8 | 51));
		// Too far from anything named: a broad area, still no number.
		assertEquals("Unmapped area", names.describe(30 << 8 | 30));
	}

	@Test
	public void aNeighbourOnTheSurfaceDoesNotNameACaveBelowIt()
	{
		RegionNames names = RegionNames.parse("Lumbridge=" + (50 << 8 | 50) + "\n");
		// 100 regions north of Lumbridge is the cave layer under it (y + 6400).
		assertEquals("under Lumbridge", names.describe(50 << 8 | 150));
		assertEquals("underground near Lumbridge", names.describe(51 << 8 | 150));
		assertEquals("Underground", RegionNames.parse("").describe(20 << 8 | 150));
	}

	@Test
	public void theWildernessSaysItsLevel()
	{
		RegionNames empty = RegionNames.parse("");
		// Surface: level = (y - 3520) / 8 + 1. Region 50,55 is y 3520-3583: levels 1-8.
		assertEquals("Wilderness lvl 1-8", empty.describe(50 << 8 | 55));
		assertEquals("Wilderness lvl 49-56", empty.describe(50 << 8 | 61));
		// Underground: level = (y - 9920) / 8 + 1. Region 52,158 is y 10112-10175: levels 25-32.
		assertEquals("Wilderness lvl 25-32 (underground)", empty.describe(52 << 8 | 158));
		// A Wilderness name nearby does not replace the level: proximity is a guess, the level is not.
		RegionNames named = RegionNames.parse("Lava Maze=" + (48 << 8 | 60) + "\n");
		assertEquals("Wilderness lvl 33-40", named.describe(48 << 8 | 59));
	}

	@Test
	public void anInstanceSaysSo()
	{
		// Instanced maps are built at x >= 6400 (region x >= 100) on the surface rows.
		assertEquals("Instance", RegionNames.parse("").describe(120 << 8 | 40));
		assertEquals("Instance", RegionNames.load().describe(120 << 8 | 40));
	}

	/** Through RegionNames' own getResourceAsStream reader; "" there means the resource did not load. */
	private static String resource(String name)
	{
		String text = RegionNames.resource(name);
		assertFalse(name + " did not load", text.isEmpty());
		return text;
	}

	@Test
	public void theFirstNameForARegionWins()
	{
		RegionNames names = RegionNames.parse("# comment\nCity=1,2\n\nDungeon=2,3\nbroken line\nBad=x,4\n");
		assertEquals("City", names.name(1));
		assertEquals("City", names.name(2));
		assertEquals("Dungeon", names.name(3));
		assertEquals("Bad", names.name(4));
		assertEquals(4, names.size());
	}
}
